"""Compile language-neutral golden inputs into a test-only Monkey C module.

No gameplay implementation is duplicated here. Expected values are reviewed
fixture data, reusable by future PWA/ESP32 implementations. --check detects drift.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def literal(value):
    if isinstance(value, dict):
        return '{'+','.join(literal(k)+'=>'+literal(v) for k, v in value.items())+'}'
    if isinstance(value, list):
        return '['+','.join(literal(v) for v in value)+']'
    return json.dumps(value, ensure_ascii=False, separators=(',', ':'))


def render():
    lines=['// Generated by prepare_rule_vectors.py; edit tests/core-vectors/*.json.',
           '(:test)', 'module RuleVectors {']
    for path in sorted((ROOT/'tests/core-vectors').glob('*.json')):
        if not path.stem.isidentifier():
            raise ValueError('Fixture filename must be an identifier')
        rows=json.loads(path.read_text())
        lines.append('    function '+path.stem+'(){return [')
        lines.append(',\n'.join('        '+literal(row) for row in rows))
        lines.append('    ];}')
    return '\n'.join(lines+['}', ''])


if __name__ == '__main__':
    parser=argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args=parser.parse_args()
    target=ROOT/'source/RuleVectors.mc'
    expected=render()
    if args.check:
        if not target.exists() or target.read_text()!=expected:
            raise SystemExit('Rule vectors out of date: run scripts/prepare_rule_vectors.py')
        print('RULE_VECTORS: checked; JSON and native fixture inputs match')
    else:
        target.write_text(expected)
        print('RULE_VECTORS: generated test-only inputs; no gameplay code generated')
