"""Generate native constants/roster from portable data, never a second engine."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def render():
    data = json.loads((ROOT/'data/battle-v1.json').read_text())
    if data['v'] != 1 or data['constants']['PROTOCOL'] != 1:
        raise ValueError('Unsupported battle data version')
    forms = data['forms']
    if [f['id'] for f in forms] != list(range(18)):
        raise ValueError('Stable form IDs changed')
    lines = ['// Generated by prepare_battle_data.py from data/battle-v1.json.',
             '// Shared data only; battle calculations remain in BeastBattleRules.',
             'module BeastBattleData {']
    for key, value in data['constants'].items():
        if not key.isidentifier() or type(value) is not int or not 0 < value < 2147483647:
            raise ValueError(f'Invalid constant {key}')
        lines.append(f'    const {key}={value};')
    lines += ['    function names(form){', '        switch(form){']
    names = []
    for form in forms:
        stage, family, rare = form['stage'], form['family'], form['rare']
        if any(type(n) is not int for n in (stage, family, rare)) or not 1 <= stage <= 5 or rare not in (0, 1) or not 0 <= family <= 4:
            raise ValueError('Invalid form metadata')
        if stage >= 3 and family == 0:
            raise ValueError('Evolved forms require a family')
        expected = stage-1 if stage in (1, 2) else 2+(family-1)*4+(3 if rare else stage-3)
        if expected != form['id'] or (stage < 3 and (family != 0 or rare)) or (rare and stage != 5):
            raise ValueError('Form metadata disagrees with stable v1 mapping')
        moves = form['moves']
        if len(moves) != 4 or any(m['id'] != form['id']*4+s or m['effect'] != s for s, m in enumerate(moves)):
            raise ValueError('Stable move/effect IDs changed')
        names.extend(m['name'] for m in moves)
        row = json.dumps([m['name'] for m in moves], ensure_ascii=True)
        lines.append(f'            case {form["id"]}:return {row};')
    if len(set(names)) != 72 or [e['id'] for e in data['effects']] != list(range(4)):
        raise ValueError('Expected 72 unique moves / four stable effect IDs')
    lines += ['        }', '        return [];', '    }',
              '    function species(form){return '+json.dumps([f['species'] for f in forms])+'[form];}',
              '    function prey(){return '+json.dumps(data['affinityPrey'])+';}', '}', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT/'source/BeastBattleData.mc'
    expected = render()
    if args.check:
        if not target.exists() or target.read_text() != expected:
            raise SystemExit('Battle data drift: run scripts/prepare_battle_data.py')
        print('BATTLE_DATA: portable definitions match native constants/roster')
    else:
        target.write_text(expected)
        print('BATTLE_DATA: generated constants/roster only; no rules generated')
