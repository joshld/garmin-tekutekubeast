"""Configure candidate QA products; NEVER advertises them in production.

One geometry/policy catalog feeds production and QA resource paths. Candidate
resource rules alone do not make a product Store eligible: manifest promotion
is a separate step after its actual SDK results have passed.
"""
import json
from pathlib import Path
import re
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
targets = json.loads((ROOT/'scripts/compatibility_candidates.json').read_text())
ns = '{http://www.garmin.com/xml/connectiq}'
ET.register_namespace('iq', ns[1:-1])
for folder in ['tests/matrix', 'tests/glance', 'tests/background', 'tests/production']:
    path = ROOT/folder/'manifest.xml'
    tree = ET.parse(path)
    products = tree.getroot().find(f'{ns}application/{ns}products')
    existing = {p.get('id') for p in products}
    for name in targets:
        if name not in existing:
            ET.SubElement(products, ns+'product', id=name)
    ET.indent(tree, space='  ')
    tree.write(path, encoding='unicode')

for folder in ['', 'tests/matrix', 'tests/glance', 'tests/background', 'tests/game-feedback', 'tests/compatibility', 'tests/production']:
    path = ROOT/folder/'monkey.jungle'
    prefix = '../../' if folder else ''
    text = re.sub(r'\n# COMPATIBILITY CANDIDATES.*', '', path.read_text(), flags=re.S).rstrip()
    # Remove the hand-written prototype rule before emitting the shared catalog.
    text = re.sub(r'(?m)^fenix6spro\.resourcePath = .*\n?', '', text).rstrip()
    text += '\n# COMPATIBILITY CANDIDATES - generated by prepare_compatibility.py\n'
    for name, (size, kind, deferred) in targets.items():
        art = ('resources-legacy-native144' if kind == 'legacyamoled' else 'resources-legacy') if kind.startswith('legacy') else ('resources-native192' if size >= 450 and kind == 'amoled' else ('resources-native144' if kind == 'amoled' else 'resources'))
        paths = [prefix+art, prefix+f'resources-world{size}']
        if folder in ('tests/matrix','tests/compatibility'): paths.append('../art-preview/resources')
        if folder == 'tests/background': paths.append('resources')
        if deferred: paths.append(prefix+'resources-deferred')
        text += f'{name}.resourcePath = '+ ';'.join(paths)+'\n'
        if deferred:
            sources = [prefix+'bin/legacy-source']
            if folder in ('tests/matrix','tests/game-feedback','tests/compatibility'): sources += ['../art-preview/source','source']
            elif folder and folder != 'tests/production': sources += ['source']
            text += f'{name}.sourcePath = '+ ';'.join(sources)+'\n'
    path.write_text(text)
print(f'Configured {len(targets)} candidates for QA; production manifest untouched')
