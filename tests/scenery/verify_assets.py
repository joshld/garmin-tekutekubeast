"""Read-only resource checks, not device/simulator certification."""
from pathlib import Path
from PIL import Image

root = Path(__file__).resolve().parents[2]
checked = 0
for size in (218, 240, 260, 280, 360, 390, 416, 454):
    for theme in ('Autumn', 'Countryside', 'Bamboo', 'Coast', 'Japanese', 'Winter'):
        for phase in ('Dawn', 'Day', 'Dusk', 'Night'):
            path = root / f'resources-world{size}/drawables/{theme}{phase}.png'
            image = Image.open(path).convert('RGBA')
            assert image.size == (size, size), path
            assert image.getpixel((size // 2, size // 5))[3] == 0, path
            pixels = {p for _, p in image.getcolors(size * size)}
            colours = {p[:3] for p in pixels if p[3]}
            assert len(colours) <= 15, (path, len(colours))
            assert all(v in (0, 85, 170, 255) for p in colours for v in p), path
            assert {p[3] for p in pixels} <= {0, 255}, path
            for slot in range(5):
                x = int(size * (.26 + .12 * slot))
                assert image.getpixel((x, int(size * .77)))[3] == 255, path
            checked += 1
print(f'PASS: {checked} native-size assets, palette/alpha/sky/ground slots')

# Generated CIQ 3.x namespace split must retain every bitmap unchanged while
# staying inside the old per-module name limit (no runtime image transforms).
import xml.etree.ElementTree as ET
from hashlib import sha256
for size in (218,240,260,280,390):
    original = root/f'resources-world{size}/drawables.xml'
    normal = root/f'bin/legacy-world{size}/drawables.xml'
    library = root/f'bin/scenery-barrel/world{size}/drawables.xml'
    if not normal.exists() or not library.exists():
        continue # Generated by build.ps1/prepare_legacy_resources.py.
    expected={b.get('id'):original.parent/b.get('filename') for b in ET.parse(original).getroot()}
    actual={}
    for catalog in (normal,library):
        for bitmap in ET.parse(catalog).getroot():
            name=bitmap.get('id');assert name not in actual, name
            actual[name]=catalog.parent/bitmap.get('filename')
    assert set(actual)==set(expected), size
    assert all(sha256(actual[n].read_bytes()).digest()==sha256(expected[n].read_bytes()).digest() for n in expected), size
    for core in ('resources-legacy','resources-legacy-native144'):
        assert len(ET.parse(root/core/'drawables/drawables.xml').getroot())+len(ET.parse(normal).getroot())<=254
print('PASS: generated legacy catalogs preserve every scenery bitmap and the 254-name limit')
